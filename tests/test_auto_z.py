"""Pure, hardware-free regression tests for experimental Optris auto-Z.

Run: python -m unittest discover -s tests -v
No USB/serial access and no movement commands are generated by these tests.
"""
import unittest
import numpy as np
from growbot_optris_auto_z import plan_z_standoff


class OptrisAutoZTests(unittest.TestCase):
    def scene(self, depth_mm=800, shape=(120, 160)):
        depth = np.full(shape, depth_mm, dtype=np.uint16)
        mask = np.zeros(shape, dtype=np.uint8)
        mask[30:90, 40:120] = 255
        return depth, mask

    def test_100mm_limit_even_for_short_plant(self):
        depth, mask = self.scene(900)
        plan = plan_z_standoff(depth, 0.001, mask,
                              target_optris_distance_mm=450)
        self.assertTrue(plan.usable)
        self.assertEqual(plan.lowering_mm, 100.0)
        self.assertAlmostEqual(plan.estimated_optris_distance_mm, 800)

    def test_retract_proposal_zero_for_near_leaves(self):
        depth, mask = self.scene(280)
        plan = plan_z_standoff(depth, 0.001, mask,
                              target_optris_distance_mm=450)
        self.assertTrue(plan.usable)
        self.assertEqual(plan.lowering_mm, 0.0)

    def test_minimum_near_leaf_clearance_caps_descent(self):
        depth, mask = self.scene(345)
        plan = plan_z_standoff(depth, 0.001, mask,
                              target_optris_distance_mm=250,
                              min_nearest_clearance_mm=300)
        self.assertTrue(plan.usable)
        self.assertEqual(plan.lowering_mm, 45.0)

    def test_offset_sign_optris_lower(self):
        depth, mask = self.scene(600)
        plan = plan_z_standoff(depth, 0.001, mask,
                              target_optris_distance_mm=550,
                              optris_minus_realsense_mm=-80)
        self.assertTrue(plan.usable)
        self.assertEqual(plan.lowering_mm, 0)

    def test_invalid_mask_never_moves(self):
        depth, mask = self.scene()
        mask[:] = 0
        plan = plan_z_standoff(depth, 0.001, mask)
        self.assertFalse(plan.usable)
        self.assertEqual(plan.lowering_mm, 0)

    def test_invalid_depth_never_moves(self):
        depth, mask = self.scene()
        depth[:] = 0
        plan = plan_z_standoff(depth, 0.001, mask)
        self.assertFalse(plan.usable)
        self.assertEqual(plan.lowering_mm, 0)

    def test_settings_can_not_request_over_100mm(self):
        depth, mask = self.scene()
        plan = plan_z_standoff(depth, 0.001, mask, max_lowering_mm=110)
        self.assertFalse(plan.usable)
        self.assertEqual(plan.lowering_mm, 0)

    def test_broad_depth_distribution_rejected(self):
        depth, mask = self.scene()
        depth[30:60, 40:120] = 300
        depth[60:90, 40:120] = 1350
        plan = plan_z_standoff(depth, 0.001, mask)
        self.assertFalse(plan.usable)
        self.assertEqual(plan.lowering_mm, 0)


if __name__ == "__main__":
    unittest.main()
